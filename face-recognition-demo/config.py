# -*- coding: utf-8 -*-
"""
config.py —— 集中存放所有可调参数

为什么把参数单独放一个文件？
    入门项目最常见的痛苦是"参数散落在代码各处，想改一个值要翻半天"。
    把它们集中到这里，你只需要改这一个文件，不用动 main.py 的逻辑。
    每一项都有中文注释说明"它是干什么的、调大调小会有什么后果"。
"""

from pathlib import Path

# ---------------------------------------------------------------------------
# 一、路径配置（用 pathlib 而不是拼字符串，跨平台更安全）
# ---------------------------------------------------------------------------
# Path(__file__).parent 表示"本文件所在的目录"，也就是项目根目录。
# 这样无论你从哪个目录启动程序，路径都指向正确的位置。
BASE_DIR = Path(__file__).resolve().parent

# 已知人脸照片 + 我提前算好的特征文件，都放在这个目录里
KNOWN_DIR = BASE_DIR / "known_faces"

# 默认的"已知人脸"照片：程序启动时会自动加载这一张
# 你可以直接把自己的照片改名为 me.jpg 覆盖它，或者改这一行指向别的文件
DEFAULT_IMAGE = KNOWN_DIR / "me.jpg"

# 备用 OpenCV(LBPH) 后端训练出来的模型缓存文件（只有走备用后端时才会生成）
LBPH_MODEL_PATH = KNOWN_DIR / "lbph_model.yml"


# ---------------------------------------------------------------------------
# 二、摄像头配置
# ---------------------------------------------------------------------------
# 摄像头编号：0 = 电脑自带摄像头；外接 USB 摄像头通常要试 1、2
CAMERA_INDEX = 0

# 采集分辨率（宽, 高）。分辨率越高画面越清楚，但每帧要算的像素更多、更卡。
# 入门机器建议 640x480；性能好的机器可以改 1280x720。
FRAME_WIDTH = 640
FRAME_HEIGHT = 480

# 水平镜像翻转：True 时画面像照镜子一样。
# 建议保持 True —— 否则你抬右手，画面里的人抬左手，看起来会很别扭。
FLIP_HORIZONTAL = True


# ---------------------------------------------------------------------------
# 三、检测与识别配置（性能与准确率的核心权衡区）
# ---------------------------------------------------------------------------
# 缩放比例：每帧先缩小再做检测，缩小后的图同时用于"算特征"。
#   人脸检测的耗时和"像素总数"成正比，缩得越小越快。
#   这是本程序能跑满帧率的关键。代价是脸太小时检测不到、且算出的特征质量下降。
#
# 怎么选这个值？（实测数据，640x480 画面）
#   人脸像素  0.25             0.35             0.5
#   ~320px     特征偏差 0.072   0.049            0.082
#   ~224px     特征偏差 0.176   0.105            0.076
#   ~128px     特征偏差 0.282   0.167            0.095
#   ~76px      检测不到         检测不到          能检测(偏差0.165)
#   （偏差 = 与"不缩放算出的特征"之间的距离，越小越好；匹配总预算只有 0.6）
#
# 实测还发现：在真实摄像头画面里，缩得越小越容易"漏掉真脸、却对背景产生假阳性"。
# 0.5 的检测召回率明显更好，代价是每帧像素量约为 0.35 的 2 倍。
# 实测 640x480 下 0.5 仍能跑到 40+ fps，所以默认用 0.5。
# 老电脑卡的话调到 0.35 或 0.25。
DETECT_SCALE = 0.5

# 人脸框最小尺寸（占画面宽度的比例）。
#   作用：挡掉背景产生的"小假阳性"。
#   实测案例：某次运行中检测器把左上角床架上的圆形物体误判成脸（约 45x45 像素，
#   占 640 宽画面的 7%），同时真脸漏检 —— 结果画面上只有一个框，还不在脸上。
#   真人脸在画面里通常占 30%~60%，所以 0.10 这个下限既能挡住误报，又不会误杀真脸。
#   如果你坐得很远、脸很小，把这个值调小（比如 0.06）；误报多就调大。
MIN_FACE_WIDTH_RATIO = 0.10

# 检测时是否把画面再放大一次（dlib 的 number_of_times_to_upsample=1）。
#   作用：等效于把检测分辨率翻倍，能显著减少"脸明明很大却检测不到"的漏检。
#   代价：检测耗时增加到约 4 倍（像素翻倍 => 面积 4 倍）。
#   实测场景：摄像头画面里人脸够大但 HOG 就是找不到，同时背景有误报时，打开它最有效。
DETECT_UPSAMPLE = 1

# 检测模型：
#   "hog" —— CPU 版，速度快，普通电脑够用（默认）
#   "cnn" —— GPU 版，更准，但需要装 CUDA 版的 dlib，否则会非常慢
DETECT_MODEL = "hog"

# 是否在画面上显示"诊断信息"（人脸框的像素尺寸、识别距离）。
#   用来排查"框不在脸上""认不出"这类问题：一看数字就知道检测到底找到了什么。
#   程序跑通之后可以改成 False，画面更干净。
SHOW_DIAGNOSTICS = True

# 识别距离阈值（face_recognition 后端专用），这是最重要的一个参数：
#   程序会给每张已知人脸算出一串 128 个数字的"特征向量"，
#   然后比较"摄像头里这张脸"和"已知人脸"这两串数字的欧氏距离。
#   距离越小 = 越像。
#   ≤ TOLERANCE  -> 判定为同一个人
#   >  TOLERANCE -> 判定为"未知"
#   0.6 是作者推荐的默认值：
#     调到 0.4 左右 -> 更严格，不容易认错人，但同一个人稍微侧脸/背光就认不出来
#     调到 0.7 左右 -> 更宽松，容易认出人，但有可能把长得像的人认错
TOLERANCE = 0.6

# 备用 OpenCV(LBPH) 后端专用的距离阈值。
# LBPH 的距离通常落在 0~100+，同样是"越小越像"，但和上面的 0.6 不是同一个量纲。
# 经验上 < 60 比较可信；如果总是认错人就把这个值调小，总是认不出就调大。
LBPH_TOLERANCE = 60.0

# "是否是同一个人"的专用阈值 —— 比 TOLERANCE 严格得多。
# 用途：录入网页判断"你上传的这张照片和已录入的是同一个人"，
#       是的话就提示"不必重复录入，可以直接跳过"。
#
# 为什么不能直接用 TOLERANCE(0.6)？因为两者的容错要求完全不同：
#   识别（TOLERANCE）宁可靠松一点，漏认比认错更烦；但"判断是否同一人"一旦判错，
#   会告诉用户"你已经录过了"，从而让他跳过录入、程序里却没有他的正确照片。
# 实测数据（本项目真实测试得出）：
#   同一人的同一张照片          0.039
#   同一人的证件照 vs 戴眼镜自拍  0.335
#   同一人的照片 vs 实时摄像头画面 0.407
#   不同的人（同龄东亚男性）      0.554   <- 用 0.6 会被误判成"同一人"
# 取 0.45 落在 0.407 和 0.554 中间，两边都留有余量。
SAME_PERSON_TOLERANCE = 0.45

# 每隔几帧做一次"识别"（而不是每帧都做）。
#   检测（找脸在哪）很便宜，识别（算特征+比对）贵得多。
#   隔帧识别 + 复用上次结果，画面更流畅，肉眼几乎感觉不到延迟。
RECOGNIZE_EVERY_N_FRAMES = 5

# 连续多少帧都识别成"同一个人"才把名字显示出来。
#   作用是消除闪烁：某一帧偶然认错，不会立刻跳到画面上。
STABLE_FRAMES = 2

# 同一个人出现多张脸时的显示名：True 显示 "张三 (2)"，False 只显示 "张三"
SHOW_COUNT_FOR_DUPLICATE = True


# ---------------------------------------------------------------------------
# 四、界面配置
# ---------------------------------------------------------------------------
UNKNOWN_LABEL = "未知"          # 陌生人的显示文字
KNOWN_COLOR = (0, 255, 0)       # 已知人脸：绿色框（注意 OpenCV 用 BGR，不是 RGB！）
UNKNOWN_COLOR = (0, 0, 255)     # 陌生人：红色框
BOX_THICKNESS = 2               # 框线粗细（像素）
FONT_SCALE = 0.6                # 英文标签字号
TEXT_THICKNESS = 1              # 文字线条粗细
SHOW_FPS = True                 # 是否在左上角显示帧率

# 是否尝试用 Pillow 渲染中文标签。
#   OpenCV 自带的 putText 只支持英文，写中文会变成一堆问号 "???"
#   所以这里用 Pillow 加载系统里的中文字体来画字。Pillow 缺失时自动退回英文标签。
USE_PILLOW_TEXT = True

# 常见中文字体路径（Windows 优先，其次 macOS / Linux）。
